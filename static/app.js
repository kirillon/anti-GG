"use strict";
const $ = id => document.getElementById(id);
let current = null;
let requestId = 0;

function invalidate() {
  requestId++;
  current = null;
  $("result").hidden = true;
  $("empty").hidden = false;
  $("empty").textContent = "Функция изменена. Постройте диаграмму заново.";
  $("badge").textContent = "Ожидает расчёта";
}

async function solve(event) {
  if (event) event.preventDefault();
  const id = ++requestId;
  $("error").hidden = true;
  $("submit").disabled = true;
  $("output").setAttribute("aria-busy", "true");
  try {
    const response = await fetch("/api/minimize", {
      method: "POST", headers: {"Content-Type": "application/json"},
      body: JSON.stringify({function: $("function").value})
    });
    const data = await response.json();
    if (id !== requestId) return;
    if (!response.ok) throw new Error(data.error || "Не удалось выполнить расчёт.");
    current = data;
    // SVG is generated by our own renderer; variable names are parsed and text is escaped.
    $("diagram").innerHTML = data.svg;
    $("result").hidden = false;
    $("empty").hidden = true;
    $("badge").textContent = "✓ Минимальность проверена";
    $("stats").textContent = `Термов: ${data.terms} · Литералов: ${data.literals}`;
    $("verification").textContent = data.ml.enabled
      ? `Модель оценила группы; выше порога: ${data.ml.proposed_groups}. Недопустимых предложений отсечено: ${data.ml.invalid_proposals}. Точный поиск проверил покрытие и минимальность.`
      : "Модель ещё не обучена. Результат рассчитан точным алгоритмом. Запустите python train.py и перезапустите приложение.";
    const table = document.createElement("table");
    const head = table.createTHead().insertRow();
    [...data.variables, "F"].forEach(label => {
      const th = document.createElement("th"); th.scope = "col"; th.textContent = label; head.append(th);
    });
    const body = table.createTBody();
    data.truth.forEach((value, i) => {
      const row = body.insertRow();
      [...data.variables.map((_, j) => (i >> (data.variables.length - 1 - j)) & 1), value]
        .forEach(bit => {row.insertCell().textContent = bit;});
    });
    $("truth-table").replaceChildren(table);
  } catch (error) {
    if (id !== requestId) return;
    current = null;
    $("result").hidden = true;
    $("empty").hidden = false;
    $("empty").textContent = "Исправьте функцию и повторите расчёт.";
    $("badge").textContent = "Ошибка ввода";
    $("error").textContent = error.message;
    $("error").hidden = false;
  } finally {
    $("submit").disabled = false;
    $("output").setAttribute("aria-busy", "false");
  }
}

function download(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url; link.download = filename; link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

$("form").addEventListener("submit", solve);
$("function").addEventListener("input", invalidate);
document.querySelectorAll("[data-example]").forEach(button => button.addEventListener("click", () => {
  $("function").value = button.dataset.example; solve();
}));
document.querySelectorAll("[data-insert]").forEach(button => button.addEventListener("click", () => {
  const input = $("function");
  input.setRangeText(button.dataset.insert, input.selectionStart, input.selectionEnd, "end");
  input.focus(); invalidate();
}));
$("svg-download").addEventListener("click", () => {
  if (current) download(new Blob([current.svg], {type:"image/svg+xml;charset=utf-8"}), "veitch.svg");
});
$("png-download").addEventListener("click", async () => {
  if (!current) return;
  const url = URL.createObjectURL(new Blob([current.svg], {type:"image/svg+xml;charset=utf-8"}));
  const img = new Image();
  try {
    img.src = url; await img.decode();
    const canvas = document.createElement("canvas");
    canvas.width = img.naturalWidth * 2; canvas.height = img.naturalHeight * 2;
    canvas.getContext("2d").drawImage(img, 0, 0, canvas.width, canvas.height);
    const blob = await new Promise(resolve => canvas.toBlob(resolve, "image/png"));
    if (!blob) throw new Error("Не удалось сохранить PNG.");
    download(blob, "veitch.png");
  } catch (error) {
    $("error").textContent = error.message; $("error").hidden = false;
  } finally { URL.revokeObjectURL(url); }
});
fetch("/api/status").then(r => r.json()).then(data => {
  $("model-status").textContent = data.model_ready ? "Собственная модель подключена" : "Модель ожидает обучения";
}).catch(() => {$("model-status").textContent = "Сервер недоступен";});
solve();
